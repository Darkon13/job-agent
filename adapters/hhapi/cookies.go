// cookieFilePath returns the shared Netscape cookie file. The backend, the
// dashboard captcha presenter and the host-side batch must all use the same
// path, otherwise HH sees several unrelated device sessions and asks for a
// captcha again after each solve.
func cookieFilePath() string {
	if path := strings.TrimSpace(os.Getenv("HH_COOKIE_FILE")); path != "" {
		return path
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".config", "job-agent", "hh-cookies.txt")
}

// persistentCookieJar keeps the exact Cookie attributes received from HH so
// they can be written back to the shared Netscape file. A plain cookiejar only
// returns name/value pairs, which loses Domain, Path and Expires.
type persistentCookieJar struct {
	base    http.CookieJar
	mu      sync.Mutex
	cookies map[string]*http.Cookie
}

func newPersistentCookieJar() *persistentCookieJar {
	base, _ := cookiejar.New(nil)
	return &persistentCookieJar{base: base, cookies: make(map[string]*http.Cookie)}
}

func cookieRecordKey(domain, path, name string) string {
	return strings.ToLower(domain) + "\x00" + path + "\x00" + name
}

func (jar *persistentCookieJar) SetCookies(target *url.URL, cookies []*http.Cookie) {
	jar.base.SetCookies(target, cookies)
	jar.mu.Lock()
	defer jar.mu.Unlock()
	for _, cookie := range cookies {
		domain := strings.ToLower(strings.TrimSpace(cookie.Domain))
		if domain == "" && target != nil {
			domain = strings.ToLower(target.Hostname())
		}
		path := strings.TrimSpace(cookie.Path)
		if path == "" {
			path = "/"
		}
		value := *cookie
		value.Domain = domain
		value.Path = path
		jar.cookies[cookieRecordKey(domain, path, cookie.Name)] = &value
	}
}

func (jar *persistentCookieJar) Cookies(target *url.URL) []*http.Cookie {
	return jar.base.Cookies(target)
}

func (jar *persistentCookieJar) export() []*http.Cookie {
	jar.mu.Lock()
	defer jar.mu.Unlock()
	now := time.Now()
	result := make([]*http.Cookie, 0, len(jar.cookies))
	for _, cookie := range jar.cookies {
		if !cookie.Expires.IsZero() && cookie.Expires.Before(now) {
			continue
		}
		value := *cookie
		result = append(result, &value)
	}
	sort.Slice(result, func(left, right int) bool {
		if result[left].Domain != result[right].Domain {
			return result[left].Domain < result[right].Domain
		}
		if result[left].Path != result[right].Path {
			return result[left].Path < result[right].Path
		}
		return result[left].Name < result[right].Name
	})
	return result
}

func cookieExporter(jar http.CookieJar) []*http.Cookie {
	if persistent, ok := jar.(*persistentCookieJar); ok {
		return persistent.export()
	}
	return nil
}

// loadCookieJar загружает Netscape cookies.txt; дальше jar сам обновляет Set-Cookie.
func loadCookieJar(path string) *persistentCookieJar {
	jar := newPersistentCookieJar()
	data, err := os.ReadFile(path)
	if err != nil {
		return jar
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 7 || !strings.Contains(fields[0], "hh.ru") {
			continue
		}
		expires := time.Time{}
		if seconds, err := strconv.ParseInt(fields[4], 10, 64); err == nil && seconds > 0 {
			expires = time.Unix(seconds, 0)
		}
		cookie := &http.Cookie{
			Name: fields[5], Value: fields[6], Path: fields[2], Domain: fields[0],
			Secure: fields[3] == "TRUE", Expires: expires,
		}
		host := strings.TrimPrefix(fields[0], ".")
		target, err := url.Parse("https://" + host + "/")
		if err != nil {
			continue
		}
		jar.SetCookies(target, []*http.Cookie{cookie})
	}
	return jar
}

// saveCookieJar writes the jar atomically with 0600 permissions. Cookies are
// secret: the file is mounted into the container and never committed.
func saveCookieJar(path string, jar http.CookieJar) error {
	if strings.TrimSpace(path) == "" || jar == nil {
		return nil
	}
	var builder strings.Builder
	builder.WriteString("# Netscape HTTP Cookie File\n")
	builder.WriteString("# Generated by job-agent; do not edit while the service is running.\n\n")
	now := time.Now()
	for _, cookie := range cookieExporter(jar) {
		domain := strings.TrimSpace(cookie.Domain)
		if domain == "" || cookie.Name == "" {
			continue
		}
		if !cookie.Expires.IsZero() && cookie.Expires.Before(now) {
			continue
		}
		pathValue := strings.TrimSpace(cookie.Path)
		if pathValue == "" {
			pathValue = "/"
		}
		includeSubdomains := "FALSE"
		if strings.HasPrefix(domain, ".") {
			includeSubdomains = "TRUE"
		}
		secure := "FALSE"
		if cookie.Secure {
			secure = "TRUE"
		}
		expiry := int64(0)
		if !cookie.Expires.IsZero() {
			expiry = cookie.Expires.Unix()
		}
		if strings.ContainsAny(cookie.Name, "\t\r\n") || strings.ContainsAny(cookie.Value, "\t\r\n") {
			continue
		}
		fmt.Fprintf(&builder, "%s\t%s\t%s\t%s\t%d\t%s\t%s\n",
			domain, includeSubdomains, pathValue, secure, expiry, cookie.Name, cookie.Value)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	temp, err := os.CreateTemp(filepath.Dir(path), ".hh-cookies-*")
	if err != nil {
		return err
	}
	tempName := temp.Name()
	defer os.Remove(tempName)
	if err := temp.Chmod(0o600); err != nil {
		temp.Close()
		return err
	}
	if _, err := temp.WriteString(builder.String()); err != nil {
		temp.Close()
		return err
	}
	if err := temp.Close(); err != nil {
		return err
	}
	return os.Rename(tempName, path)
}

// mergeCookieJar copies cookies from source into destination without removing
// destination cookies that are newer or absent from the file.
func mergeCookieJar(destination, source http.CookieJar) {
	if destination == nil || source == nil {
		return
	}
	for _, cookie := range cookieExporter(source) {
		host := strings.TrimPrefix(strings.TrimSpace(cookie.Domain), ".")
		if host == "" {
			continue
		}
		target, err := url.Parse("https://" + host + "/")
		if err != nil {
			continue
		}
		destination.SetCookies(target, []*http.Cookie{cookie})
	}
}

// reloadCookies merges a cookie file written by another process (dashboard
// captcha presenter or the host-side batch) into the running client jar.
func (c *Client) reloadCookies() {
	if c == nil || c.cookieFile == "" {
		return
	}
	info, err := os.Stat(c.cookieFile)
	if err != nil {
		return
	}
	c.cookieMu.Lock()
	defer c.cookieMu.Unlock()
	if !info.ModTime().After(c.cookieModTime) {
		return
	}
	mergeCookieJar(c.cookies, loadCookieJar(c.cookieFile))
	c.cookieModTime = info.ModTime()
}

// saveCookies persists the current anti-bot cookies. A small throttle keeps a
// busy search client from rewriting the file on every page; captcha and apply
// paths force the write.
func (c *Client) saveCookies(force bool) {
	if c == nil || c.cookieFile == "" || c.cookies == nil {
		return
	}
	c.cookieMu.Lock()
	defer c.cookieMu.Unlock()
	now := time.Now()
	if !force && now.Sub(c.lastCookieSave) < 30*time.Second {
		return
	}
	if err := saveCookieJar(c.cookieFile, c.cookies); err != nil {
		return
	}
	c.lastCookieSave = now
	if info, err := os.Stat(c.cookieFile); err == nil {
		c.cookieModTime = info.ModTime()
	}
}
